const byId = new Map(foods.map((f) => [f.id, f]))

const RECIPE_PREFIX = 'recipe:'

/** Diary id for a logged recipe serving — recipes resolve to foods on the fly. */
export function recipeFoodId(recipeId: string) {
  return `${RECIPE_PREFIX}${recipeId}`
}

export function getFood(id: string): Food | undefined {
  if (!id.startsWith(RECIPE_PREFIX)) return byId.get(id)
  const recipe = getRecipe(id.slice(RECIPE_PREFIX.length))
  if (!recipe) return undefined
  return {
    id,
    name: recipe.title,
    category: 'Bowls',
    photo: recipe.photo,
    emoji: '🍽️',
    serving: { label: '1 serving', grams: 350 },
    nutrients: recipe.nutrients,
    micros: {},
    score: 88,
    tags: recipe.tags.slice(0, 2),
    verified: true,
  }
}

