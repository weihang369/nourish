const byId = new Map(recipes.map((r) => [r.id, r]))

export function getRecipe(id: string) {
  return byId.get(id)
}

export function filterRecipes(filter: RecipeFilter, query = '') {
  const q = query.trim().toLowerCase()
  return recipes.filter((r) => {
    const matchesFilter = filter === 'For you' || r.tags.includes(filter)
    const matchesQuery = !q || r.title.toLowerCase().includes(q) || r.tags.some((t) => t.toLowerCase().includes(q))
    return matchesFilter && matchesQuery
  })
}
